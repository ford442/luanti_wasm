"""Write the launcher-config.js a deployment ships: its hosted proxy regions.

The repository's client/web/launcher-config.js stays empty (no proxy hostname
belongs in the client source). A deployment writes its own and hands it to the
build, which hashes it into the release like every other shell file:

  python3 util/wasm/write_launcher_config.py --output build-config/launcher-config.js \\
      --proxy eu=Europe=wss://proxy.example.org/ --default eu
  cmake --preset Emscripten -DLUANTI_WEB_LAUNCHER_CONFIG=$PWD/build-config/launcher-config.js

--proxy is ID=LABEL=URL, or ID=LABEL=URL=EXPIRES, repeatable. EXPIRES (an ISO
date or timestamp) is the deployment owner's own end date: from then on the
launcher stops offering that region (see doc/compiling/wasm-embedding.md).
The same values can come from the environment, which is how CI passes them
(--from-env): LUANTI_WEB_PROXY_ID, _LABEL, _URL, _EXPIRES and LUANTI_WEB_SERVER_LIST_URL.

Nothing secret goes in this file: it is public. Proxy URLs must be wss://,
because an HTTPS page cannot open ws://, and must name a host only.
"""

from __future__ import annotations

import argparse
from datetime import datetime
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit

HEADER = """// Luanti
// SPDX-License-Identifier: LGPL-2.1-or-later
// Copyright (C) 2026 The Luanti Contributors

// Generated by util/wasm/write_launcher_config.py for this deployment. It is
// public: never put credentials in it. A proxy that is not on the player's own
// machine can read their gameplay and chat; the launcher says so.
"""
ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]{0,31}$")
DEFAULT_SERVER_LIST = "https://servers.luanti.org/list.json"


class ConfigError(ValueError):
	pass


def parse_expiry(value: str) -> str:
	"""An ISO date or timestamp, kept as the owner wrote it once it parses."""
	text = value.strip()
	try:
		datetime.fromisoformat(text.replace("Z", "+00:00"))
	except ValueError as error:
		raise ConfigError(f"expires must be an ISO date or timestamp, got {value!r}") from error
	return text


def parse_proxy(spec: str, *, allow_insecure: bool = False) -> dict[str, str]:
	parts = spec.split("=", 3)
	if len(parts) < 3:
		raise ConfigError(f"--proxy wants ID=LABEL=URL[=EXPIRES], got {spec!r}")
	identifier, label, url = (part.strip() for part in parts[:3])
	if not ID_PATTERN.fullmatch(identifier):
		raise ConfigError(f"proxy id {identifier!r} must be lowercase letters, digits, - or _")
	if not label or len(label) > 60 or any(ord(character) < 32 for character in label):
		raise ConfigError(f"proxy {identifier}: the label must be 1-60 printable characters")
	address = urlsplit(url)
	allowed = ("wss",) + (("ws",) if allow_insecure else ())
	if address.scheme not in allowed:
		raise ConfigError(f"proxy {identifier}: {url!r} must be wss:// (an HTTPS page cannot open ws://)")
	if not address.hostname or address.username or address.password or address.query or address.fragment:
		raise ConfigError(f"proxy {identifier}: {url!r} must name a host only (no credentials, query or fragment)")
	entry = {"id": identifier, "label": label, "url": url}
	if len(parts) == 4 and parts[3].strip():
		entry["expires"] = parse_expiry(parts[3])
	return entry


def render(proxies: list[dict[str, str]], default: str, server_list_url: str) -> str:
	ids = [proxy["id"] for proxy in proxies]
	if len(set(ids)) != len(ids):
		raise ConfigError("proxy ids must be unique")
	default_url = ""
	if default:
		match = next((proxy for proxy in proxies if proxy["id"] == default), None)
		if not match:
			raise ConfigError(f"--default {default!r} is not one of the proxies: {', '.join(ids) or 'none'}")
		default_url = match["url"]
	config = {"serverListUrl": server_list_url, "defaultProxy": default_url, "proxies": proxies}
	return HEADER + "window.LUANTI_WEB_CONFIG = " + json.dumps(config, indent="\t") + ";\n"


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(description=__doc__,
		formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--output", required=True, help="where to write launcher-config.js")
	parser.add_argument("--proxy", action="append", default=[], metavar="ID=LABEL=URL[=EXPIRES]")
	parser.add_argument("--default", default="", metavar="ID",
		help="the region the launcher preselects (default: none, so the player chooses)")
	parser.add_argument("--server-list-url", default=DEFAULT_SERVER_LIST)
	parser.add_argument("--from-env", action="store_true", help="read one region from LUANTI_WEB_PROXY_*")
	parser.add_argument("--allow-insecure", action="store_true",
		help="accept ws:// proxies (local testing only; an HTTPS page refuses them)")
	args = parser.parse_args(argv)

	specs = list(args.proxy)
	default = args.default
	server_list = args.server_list_url
	if args.from_env:
		url = os.environ.get("LUANTI_WEB_PROXY_URL", "").strip()
		if url:
			identifier = os.environ.get("LUANTI_WEB_PROXY_ID", "").strip() or "default"
			label = os.environ.get("LUANTI_WEB_PROXY_LABEL", "").strip() or identifier
			expires = os.environ.get("LUANTI_WEB_PROXY_EXPIRES", "").strip()
			specs.append(f"{identifier}={label}={url}" + (f"={expires}" if expires else ""))
			default = default or identifier
		server_list = os.environ.get("LUANTI_WEB_SERVER_LIST_URL", "").strip() or server_list
	try:
		proxies = [parse_proxy(spec, allow_insecure=args.allow_insecure) for spec in specs]
		text = render(proxies, default, server_list)
	except ConfigError as error:
		print(f"write_launcher_config.py: {error}", file=sys.stderr)
		return 2
	output = Path(args.output)
	output.parent.mkdir(parents=True, exist_ok=True)
	output.write_text(text, encoding="utf-8")
	print(f"wrote {output} ({len(proxies)} proxy region(s)"
		+ (f", default {default}" if default else "") + ")")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
